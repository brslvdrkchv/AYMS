const I18n = {
  currentLang: 'uk',

  init() {
    if (typeof document === 'undefined') return;
    const urlParams = new URLSearchParams(window.location.search);
    const urlLang = urlParams.get('lang');
    const savedLang = localStorage.getItem('ayms_lang');

    let initialLang = 'uk';
    if (urlLang === 'en' || urlLang === 'uk') {
      initialLang = urlLang;
    } else if (savedLang === 'en' || savedLang === 'uk') {
      initialLang = savedLang;
    }

    this.setLanguage(initialLang, false);
    this.bindSwitchers();
  },

  bindSwitchers() {
    if (typeof document === 'undefined') return;
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        const targetLang = btn.getAttribute('data-lang');
        if (targetLang && (targetLang === 'uk' || targetLang === 'en')) {
          this.setLanguage(targetLang, true);
        }
      });
    });
  },

  setLanguage(lang, save = true) {
    if (!TRANSLATIONS[lang]) return;
    this.currentLang = lang;

    if (typeof document === 'undefined') return;

    document.documentElement.setAttribute('lang', lang);
    document.body.setAttribute('data-lang', lang);

    if (save) {
      try {
        localStorage.setItem('ayms_lang', lang);
      } catch (e) {}
    }

    const dict = TRANSLATIONS[lang];

    if (dict.page_title) {
      document.title = dict.page_title;
    }
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && dict.page_description) {
      metaDesc.setAttribute('content', dict.page_description);
    }

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
      const isMatch = btn.getAttribute('data-lang') === lang;
      btn.classList.toggle('active', isMatch);
      btn.setAttribute('aria-pressed', isMatch ? 'true' : 'false');
    });

    // Seamlessly swap 1:1 Figma graphic sections for mobile
    const sec1 = document.querySelector('#m-hero .section-bg');
    const sec2 = document.querySelector('#m-about .section-bg');
    const sec3 = document.querySelector('#m-organizers .section-bg');
    if (sec1 && sec2 && sec3) {
      if (lang === 'en') {
        sec1.src = 'images/figma_sections_en/sec_1_hero.webp?v=20261030_01';
        sec2.src = 'images/figma_sections_en/sec_2_about.webp?v=20261030_01';
        sec3.src = 'images/figma_sections_en/sec_3_organizers.webp?v=20261030_01';
      } else {
        sec1.src = 'images/figma_sections/sec_1_hero.webp?v=20261030_01';
        sec2.src = 'images/figma_sections/sec_2_about.webp?v=20261030_01';
        sec3.src = 'images/figma_sections/sec_3_organizers.webp?v=20261030_01';
      }
    }

    const modalContainer = document.getElementById('modal-container');
    if (modalContainer && modalContainer.classList.contains('active') && modalContainer.dataset.activeType) {
      const activeType = modalContainer.dataset.activeType;
      const modalData = this.getModalData(activeType);
      if (modalData) {
        const modalTitle = document.getElementById('modal-title');
        const modalBody = document.getElementById('modal-body');
        if (modalTitle) modalTitle.textContent = modalData.title;
        if (modalBody) modalBody.innerHTML = modalData.content;
      }
    }

    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  },

  getModalData(type) {
    const langModals = MODAL_TRANSLATIONS[this.currentLang] || MODAL_TRANSLATIONS.uk;
    return langModals[type] || null;
  }
};

if (typeof window !== 'undefined') {
  window.I18n = I18n;
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => I18n.init());
  } else {
    I18n.init();
  }
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { TRANSLATIONS, MODAL_TRANSLATIONS, I18n };
}
